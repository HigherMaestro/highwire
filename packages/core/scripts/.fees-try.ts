import { Chain, HigherApi, createHttpConfig, DEFAULT_API_URL, ecosystemFees } from "../src/index.ts";
const chain = new Chain({ cluster: "mainnet", rpcUrl: process.env.SOLANA_RPC_URL });
const api = new HigherApi(createHttpConfig({ baseUrl: DEFAULT_API_URL, timeoutMs: 10_000, retries: 1, userAgent: "highwire-dev" }));
const t = Date.now();
const r = await ecosystemFees(chain, api);
console.log(`${Date.now() - t} ms`);
console.log(JSON.stringify({ totals: r.totals, waiting: r.waiting, rates: r.rates, warnings: r.warnings, solUsd: r.solUsd }, null, 1));
for (const c of r.coins.slice(0, 6)) console.log(c.ticker, c.feeMode, c.status, c.volumeSol.toFixed(1), c.totalFeesSol.toFixed(3), JSON.stringify(c.byRecipient), JSON.stringify(c.pool));
const high = r.coins.find((c) => c.ticker === "HIGH");
console.log(JSON.stringify(high?.lines, null, 1));
