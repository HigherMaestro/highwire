#!/usr/bin/env bash
# Builds the rig's WebAssembly (src/wasm/sameboy.mjs) from SameBoy 1.0.3's core and native/rig.c, in a pinned
# Emscripten container, so nothing but Docker is needed and CI and Vercel never build it: the output is committed with
# its checksum (src/wasm/sameboy.sha256). Run it only when rig.c, the version or the flags change:
#   npm run build-wasm -w highwire-link
set -euo pipefail

SAMEBOY_VERSION=1.0.3
SAMEBOY_SHA256=7da338458e19396cb43dfe1a4df4555882ebea92540565dc993c1c706c981dc3
# emscripten/emsdk:6.0.13 (2026-10-19), by digest.
EMSDK_IMAGE=emscripten/emsdk@sha256:fb7864e398acfda863dfcea78b8bc8adad359fa60c6a0bbeb845931de64aa68a

here="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -sSL --fail -o "$work/sameboy.tar.gz" "https://github.com/LIJI32/SameBoy/archive/refs/tags/v${SAMEBOY_VERSION}.tar.gz"
echo "${SAMEBOY_SHA256}  $work/sameboy.tar.gz" | shasum -a 256 -c -
tar xzf "$work/sameboy.tar.gz" -C "$work"
mkdir -p "$here/src/wasm"

CORE=(gb sgb apu memory mbc timing display camera sm83_cpu joypad save_state random rumble)
CORE_FILES=()
for f in "${CORE[@]}"; do CORE_FILES+=("SameBoy-${SAMEBOY_VERSION}/Core/$f.c"); done

FUNCS='["_rig_init","_rig_load_rom","_rig_state_size","_rig_save_state","_rig_load_state","_rig_run_frames","_rig_set_key","_rig_read","_rig_write","_rig_direct","_rig_last_size","_rig_set_rendering","_rig_pixels","_rig_model","_rig_stopped","_rig_mid_frame","_rig_watch","_rig_watch_clear","_rig_seq","_rig_pc","_rig_cable_get","_rig_cable_set","_malloc","_free"]'

BUILD="
  set -e
  cd \"\$SRC\"
  emcc -O3 -std=gnu11 -D_GNU_SOURCE -DNDEBUG \
    -DGB_DISABLE_TIMEKEEPING -DGB_DISABLE_REWIND -DGB_DISABLE_DEBUGGER -DGB_DISABLE_CHEATS -DGB_DISABLE_CHEAT_SEARCH \
    -DGB_VERSION='\"${SAMEBOY_VERSION}\"' -DGB_COPYRIGHT_YEAR='\"2026\"' -DGB_INTERNAL \
    -I SameBoy-${SAMEBOY_VERSION} -Wno-everything -c ${CORE_FILES[*]}
  emcc -O3 -std=gnu11 -I SameBoy-${SAMEBOY_VERSION} -c \"\$LINK/native/rig.c\" -o rig.o
  emcc -O3 *.o -o \"\$LINK/src/wasm/sameboy.mjs\" \
    -sMODULARIZE=1 -sEXPORT_ES6=1 -sSINGLE_FILE=1 -sENVIRONMENT=node \
    -sALLOW_MEMORY_GROWTH=1 -sFILESYSTEM=0 -sEXPORT_NAME=createSameBoy \
    -sEXPORTED_FUNCTIONS='${FUNCS}' -sEXPORTED_RUNTIME_METHODS='[\"HEAPU8\",\"HEAPU32\"]'
"

# Emscripten 6.0.13 either from an activated emsdk (EMSDK set: `./emsdk install 6.0.13 && ./emsdk activate 6.0.13`,
# then `source ./emsdk_env.sh`), or from the pinned container. Both are the same release; the version is checked.
if [ -n "${EMSDK:-}" ] && command -v emcc >/dev/null; then
  emcc --version | head -1 | grep -q " 6\.0\.13 " || { echo "emcc isn't 6.0.13" >&2; exit 1; }
  SRC="$work" LINK="$here" bash -c "$BUILD"
else
  docker run --rm -v "$work:/src" -v "$here:/link" -e SRC=/src -e LINK=/link "$EMSDK_IMAGE" bash -c "$BUILD"
fi
(cd "$here/src/wasm" && shasum -a 256 sameboy.mjs > sameboy.sha256)
printf '// Generated by scripts/build-wasm.sh with the build: the SHA-256 of sameboy.mjs, so saved states name the emulator\n// that made them (test/boundary.test.ts checks it matches). Never edit by hand.\nexport const WASM_SHA256 = "%s";\n' \
  "$(cut -c1-64 "$here/src/wasm/sameboy.sha256")" > "$here/src/wasm/version.ts"
echo "Built src/wasm/sameboy.mjs ($(wc -c < "$here/src/wasm/sameboy.mjs") bytes)"
